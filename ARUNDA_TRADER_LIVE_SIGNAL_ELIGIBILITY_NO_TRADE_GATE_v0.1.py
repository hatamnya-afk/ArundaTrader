def load_latest_snapshot(conn):
    row = conn.execute(
        """
        SELECT snapshot_id, MAX(timestamp)
        FROM fusion_signals
        WHERE engine_version = ?
          AND snapshot_id IS NOT NULL
        GROUP BY snapshot_id
        ORDER BY MAX(timestamp) DESC
        LIMIT 1
        """,
        (EXPECTED_ENGINE,),
    ).fetchone()

    if not row:
        raise RuntimeError("No FUSION_v0.5 snapshot found.")

    snapshot_id = row[0]

    rows = conn.execute(
        """
        SELECT
            id,
            timestamp,
            asset,
            market_available,
            positioning_available,
            news_available,
            available_weight,
            missing_arm_penalty,
            data_quality,
            direction,
            confidence,
            regime,
            signal_strength,
            entry_price,
            fused_score,
            snapshot_id,
            engine_version
        FROM fusion_signals
        WHERE snapshot_id = ?
          AND engine_version = ?
        ORDER BY id
        """,
        (snapshot_id, EXPECTED_ENGINE),
    ).fetchall()

    return snapshot_id, rows


# --------------------------------------------------------------------------------------------------
# ROW ELIGIBILITY
# --------------------------------------------------------------------------------------------------

def evaluate_row(row):
    (
        row_id,
        timestamp,
        asset,
        market_available,
        positioning_available,
        news_available,
        available_weight,
        missing_arm_penalty,
        data_quality,
        direction,
        confidence,
        regime,
        signal_strength,
        entry_price,
        fused_score,
        snapshot_id,
        engine_version,
    ) = row

    reasons = []

    # ----------------------------------------------------------------------------------------------
    # HARD INPUT SAFETY
    # ----------------------------------------------------------------------------------------------

    if engine_version != EXPECTED_ENGINE:
        reasons.append("ENGINE_MISMATCH")

    if not snapshot_id:
        reasons.append("MISSING_SNAPSHOT_ID")

    if not asset:
        reasons.append("MISSING_ASSET")

    if not timestamp:
        reasons.append("MISSING_TIMESTAMP")

    if entry_price is None:
        reasons.append("MISSING_ENTRY_PRICE")
    elif entry_price <= 0:
        reasons.append("INVALID_ENTRY_PRICE")

    if confidence is None:
        reasons.append("MISSING_CONFIDENCE")
    elif confidence < MIN_CONFIDENCE:
        reasons.append("CONFIDENCE_BELOW_GATE")

    if available_weight is None:
        reasons.append("MISSING_AVAILABLE_WEIGHT")
    elif available_weight < MIN_AVAILABLE_WEIGHT:
        reasons.append("INSUFFICIENT_AVAILABLE_WEIGHT")

    if data_quality != REQUIRED_DATA_QUALITY:
        reasons.append("DATA_QUALITY_NOT_VERIFIED")

    if direction not in ALLOWED_DIRECTIONS:
        if direction in BLOCKED_DIRECTIONS:
            reasons.append("FLAT_DIRECTION")
        else:
            reasons.append("INVALID_DIRECTION")

    if signal_strength in BLOCKED_SIGNAL_STRENGTH:
        reasons.append("WEAK_SIGNAL")

    if signal_strength is None:
        reasons.append("MISSING_SIGNAL_STRENGTH")

    if regime is None:
        reasons.append("MISSING_REGIME")

    # ----------------------------------------------------------------------------------------------
    # ARM SAFETY
    # ----------------------------------------------------------------------------------------------

    arms = [
        market_available,
        positioning_available,
        news_available,
    ]

    if any(x is None for x in arms):
        reasons.append("UNKNOWN_ARM_STATE")

    # Conservative rule:
    # all three arms must be available before trade eligibility.
    if not all(x == 1 for x in arms if x is not None):
        reasons.append("INCOMPLETE_ARM_SET")

    # ----------------------------------------------------------------------------------------------
    # FINAL DECISION
    # ----------------------------------------------------------------------------------------------

    eligible = len(reasons) == 0

    if eligible:
        status = "TRADE_ELIGIBLE"
    else:
        status = "NO_TRADE"

    return {
        "id": row_id,
        "asset": asset,
        "timestamp": timestamp,
        "direction": direction,
        "confidence": confidence,
        "regime": regime,
        "signal_strength": signal_strength,
        "data_quality": data_quality,
        "entry_price": entry_price,
        "available_weight": available_weight,
        "missing_arm_penalty": missing_arm_penalty,
        "market_available": market_available,
        "positioning_available": positioning_available,
        "news_available": news_available,
        "status": status,
        "eligible": eligible,
        "reasons": reasons,
    }


# --------------------------------------------------------------------------------------------------
# REPORT
# --------------------------------------------------------------------------------------------------

def build_report(
    production_before,
    production_after,
    capture_db,
    snapshot_id,
    evaluations,
):
    eligible = [
        x for x in evaluations
        if x["eligible"]
    ]

    no_trade = [
        x for x in evaluations
        if not x["eligible"]
    ]

    return {
        "frontier": "LIVE_SIGNAL_ELIGIBILITY_NO_TRADE_GATE_v0.1",
        "timestamp_utc": utc_now().isoformat(),

        "production_db": {
            "path": PRODUCTION_DB,
            "before": production_before,
            "after": production_after,
            "unchanged": (
                production_before == production_after
            ),
        },

        "capture_db": capture_db,

        "engine": EXPECTED_ENGINE,

        "snapshot_id": snapshot_id,

        "gate_configuration": {
            "min_confidence": MIN_CONFIDENCE,
            "min_available_weight": MIN_AVAILABLE_WEIGHT,
            "required_data_quality": REQUIRED_DATA_QUALITY,
            "required_safety": REQUIRED_SAFETY,
            "blocked_signal_strength": sorted(
                BLOCKED_SIGNAL_STRENGTH
            ),
            "blocked_directions": sorted(
                BLOCKED_DIRECTIONS
            ),
            "required_arms": [
                "market",
                "positioning",
                "news",
            ],
        },

        "rows": len(evaluations),

        "eligible_rows": len(eligible),

        "no_trade_rows": len(no_trade),

        "decision": (
            "TRADE_CANDIDATES_PRESENT"
            if eligible
            else "NO_TRADE"
        ),

        "row_results": evaluations,

        "safety": {
            "production_db_modified": False,
            "engine_executed": False,
            "historical_repair": False,
            "direction_inference": False,
            "score_reconstruction": False,
            "synthetic_data": False,
            "live_data_injection": False,
            "order_execution": False,
        },
    }


