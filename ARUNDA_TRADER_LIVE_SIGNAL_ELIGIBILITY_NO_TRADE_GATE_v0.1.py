def sha256_file(path):
    h = hashlib.sha256()

    with open(path, "rb") as f:
        while True:
            chunk = f.read(1024 * 1024)

            if not chunk:
                break

            h.update(chunk)

    return h.hexdigest()


def find_latest_capture():
    candidates = []

    if not os.path.isdir(CAPTURE_ROOT):
        return None

    for name in os.listdir(CAPTURE_ROOT):

        if not name.startswith("arunda_live_launch_"):
            continue

        path = os.path.join(CAPTURE_ROOT, name)

        if not os.path.isdir(path):
            continue

        db_path = os.path.join(path, "arunda_live_capture.db")

        if not os.path.isfile(db_path):
            continue

        try:
            mtime = os.path.getmtime(db_path)
            candidates.append((mtime, path, db_path))
        except OSError:
            pass

    if not candidates:
        return None

    candidates.sort(reverse=True)

    return candidates[0][1], candidates[0][2]


def open_readonly(path):
    uri = "file:" + path.replace("\\", "/") + "?mode=ro"
    return sqlite3.connect(uri, uri=True)


def get_columns(conn):
    rows = conn.execute(
        "PRAGMA table_info(fusion_signals)"
    ).fetchall()

    return {row[1] for row in rows}


def utc_now():
    return datetime.now(timezone.utc)


# --------------------------------------------------------------------------------------------------
# PRODUCTION BASELINE
# --------------------------------------------------------------------------------------------------

def production_baseline():
    size = os.path.getsize(PRODUCTION_DB)
    digest = sha256_file(PRODUCTION_DB)

    conn = open_readonly(PRODUCTION_DB)

    try:
        rows = conn.execute(
            "SELECT COUNT(*) FROM fusion_signals"
        ).fetchone()[0]
    finally:
        conn.close()

    return {
        "size": size,
        "sha256": digest,
        "rows": rows,
    }


